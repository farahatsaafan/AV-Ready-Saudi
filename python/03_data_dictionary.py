"""
AV-Ready-Saudi - rebuild the data dictionary from the DDL.

Reads every CREATE TABLE in sql/01_bronze.sql, sql/02_silver.sql and sql/03_gold.sql and writes
docs/data_dictionary.csv and docs/02_data_dictionary.md. A column's description is taken, in order,
from: docs/data_dictionary_descriptions.csv (hand-written), the inline "-- comment" in the DDL, or the
previous docs/data_dictionary.csv. Columns left without a description are listed at the end.

Usage (from the project folder):  python3 python/03_data_dictionary.py
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SQL = [ROOT / "sql" / f for f in ("01_bronze.sql", "02_silver.sql", "03_gold.sql")]
OUT_CSV = ROOT / "docs" / "data_dictionary.csv"
OUT_MD = ROOT / "docs" / "02_data_dictionary.md"
EXTRA = ROOT / "docs" / "data_dictionary_descriptions.csv"
LAYER = {"bronze": "Bronze", "silver": "Silver", "prep": "prep (Gold work)", "gold": "Gold"}


def old_descriptions() -> dict:
    d = {}
    for path in (OUT_CSV, EXTRA):
        if path.exists():
            for r in csv.DictReader(open(path, newline="", encoding="utf-8")):
                if r.get("description"):
                    d[(r["table"], r["column"])] = r["description"]
    return d


def parse(text: str):
    for m in re.finditer(r"CREATE TABLE\s+(\w+)\.(\w+)\s*\((.*?)\n\);", text, re.S):
        schema, table, body = m.group(1), m.group(2), m.group(3)
        pk = set()
        for k in re.findall(r"PRIMARY KEY\s*\(([^)]*)\)", body):
            pk |= {c.strip().strip("[]") for c in k.split(",")}
        cols = []
        for line in body.split("\n"):
            code, _, comment = line.partition("--")
            for part in re.split(r",\s*(?=\[?\w[\w ()]*\]?\s+(?:N?VARCHAR|N?CHAR|INT|BIGINT|SMALLINT|TINYINT|BIT|FLOAT|DATE|DATETIME2|DECIMAL|UNIQUEIDENTIFIER))", code.strip().rstrip(",")):
                part = part.strip().rstrip(",")
                mm = re.match(r"(\[[^\]]+\]|\w+)\s+((?:N?VARCHAR|N?CHAR|DECIMAL)\s*\([^)]*\)|(?:DATETIME2|TIME)\s*(?:\(\d\))?|\w+)(.*)", part)
                if not mm or mm.group(1).upper() in ("PRIMARY", "CONSTRAINT", "FOREIGN", "UNIQUE"):
                    continue
                name, dtype, rest = mm.group(1).strip("[]"), re.sub(r"\s+", "", mm.group(2)), mm.group(3)
                inline_pk = "PRIMARY KEY" in rest.upper()
                nullable = "NO" if ("NOT NULL" in rest.upper() or inline_pk) else "YES"
                key = "PK" if (inline_pk or name in pk) else ("FK" if "REFERENCES" in rest.upper() else "")
                cols.append((name, dtype, nullable, key, comment.strip()))
        yield schema, table, cols


def main() -> None:
    old = old_descriptions()
    rows, missing = [], []
    for f in SQL:
        for schema, table, cols in parse(f.read_text(encoding="utf-8")):
            full = f"{schema}.{table}"
            for name, dtype, nullable, key, comment in cols:
                desc = old.get((full, name)) or comment
                if not desc:
                    missing.append(f"{full}.{name}")
                rows.append(dict(layer=LAYER.get(schema, schema), table=full, column=name, data_type=dtype,
                                 nullable=nullable, key=key, description=desc))
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader(); w.writerows(rows)
    md = ["# Data Dictionary — AV-Ready-Saudi", "",
          "Generated by `python/03_data_dictionary.py` from the DDL in `sql/01_bronze.sql`, `sql/02_silver.sql`, "
          "`sql/03_gold.sql` (same content as `docs/data_dictionary.csv`).",
          "Bronze columns are all text by design; Silver/prep/Gold are typed.", ""]
    current = None
    for r in rows:
        if r["table"] != current:
            current = r["table"]
            md += ["", f"## {current} ({r['layer']})", "", "| Column | Type | Null | Description |", "|---|---|---|---|"]
        key = f" ({r['key']})" if r["key"] else ""
        md.append(f"| `{r['column']}`{key} | {r['data_type']} | {r['nullable']} | {r['description'].replace('|', '/')} |")
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} columns in {len({r['table'] for r in rows})} tables")
    if missing:
        print("no description:", *missing, sep="\n  ")


if __name__ == "__main__":
    main()
